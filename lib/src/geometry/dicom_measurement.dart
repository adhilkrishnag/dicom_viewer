import 'package:flutter/foundation.dart';
import 'image_coordinate_transform.dart';

/// The type discriminator for a DICOM measurement.
enum DicomMeasurementType {
  /// 2D caliper distance measurement between two points.
  distance,

  /// 2D rectangular Region of Interest (ROI) measurement with pixel statistics.
  rectangleRoi,
}

/// Abstract common interface for all 2D measurements on a DICOM image frame.
///
/// Provides a unified model across different measurement shapes (caliper distances,
/// rectangular ROIs, etc.) with:
/// - A stable unique [id] independent of collection position.
/// - A [type] discriminator ([DicomMeasurementType]).
/// - An associated [frameIndex] (0-indexed).
/// - An underlying [geometry] representation in native image coordinates.
/// - Independent [isVisible] and [isSelected] state flags.
/// - Geometric validity flag [isValid].
/// - User-facing formatted value string [formattedValue].
/// - Accessibility label [semanticsLabel].
abstract class DicomMeasurement {
  /// Stable unique identifier for this measurement.
  String get id;

  /// The type discriminator for this measurement.
  DicomMeasurementType get type;

  /// The multi-frame image index (0-indexed) this measurement belongs to.
  int get frameIndex;

  /// The geometric representation of this measurement in native image coordinates.
  ///
  /// The geometry type is intentionally measurement-specific at this stage (e.g.,
  /// [DicomLineGeometry] for distance calipers, [Rect] for rectangular ROIs).
  /// Concrete implementations return their strongly typed geometry covariantly.
  Object get geometry;

  /// Whether this measurement is visible on the image overlay.
  bool get isVisible;

  /// Whether this measurement is currently selected.
  bool get isSelected;

  /// Whether this measurement is geometrically valid and inside image bounds.
  bool get isValid;

  /// User-facing formatted value / dimension string.
  String get formattedValue;

  /// Accessibility-friendly label for screen readers.
  String get semanticsLabel;

  /// Creates a copy of this measurement with updated visibility or selection state.
  DicomMeasurement copyWithMeasurement({bool? isVisible, bool? isSelected});
}

/// A lightweight representation of a 2D line segment between two [ImagePoint]s.
class DicomLineGeometry {
  /// Creates a [DicomLineGeometry] between [start] and [end].
  const DicomLineGeometry({required this.start, required this.end});

  /// Starting point in continuous native image coordinates.
  final ImagePoint start;

  /// Ending point in continuous native image coordinates.
  final ImagePoint end;

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is DicomLineGeometry &&
          runtimeType == other.runtimeType &&
          start == other.start &&
          end == other.end;

  @override
  int get hashCode => start.hashCode ^ end.hashCode;

  @override
  String toString() => 'DicomLineGeometry(start: $start, end: $end)';
}

/// Monotonic ID generator for assigning stable unique measurement IDs when not explicitly provided.
///
/// ## Uniqueness & Stability Contract
/// - **Session Uniqueness**: IDs generated by [generate] are guaranteed unique within the
///   active application/viewer session by combining a prefix, microsecond timestamp, and
///   monotonic counter (`${prefix}_${microseconds}_${counter}`).
/// - **Stability**: An assigned ID remains fixed for the lifetime of that measurement,
///   independent of its position within collection lists or reordering/deletion of peers.
/// - **Explicit IDs**: Callers with domain-specific identities (such as DICOM SOP Instance
///   UIDs or Presentation State Annotation sequence items) can provide explicit IDs via
///   constructors without relying on this generator.
class DicomMeasurementIdGenerator {
  static int _counter = 0;

  /// Generates a stable unique ID with the specified [prefix].
  static String generate([String prefix = 'm']) {
    _counter++;
    return '${prefix}_${DateTime.now().microsecondsSinceEpoch}_$_counter';
  }

  /// Resets the counter (primarily for deterministic unit testing).
  @visibleForTesting
  static void resetForTesting() {
    _counter = 0;
  }
}
